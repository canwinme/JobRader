CREATE TABLE TB_INDUSTRY_VACANCY (
    PERIOD_YEAR      NUMBER(4)      NOT NULL,
    PERIOD_HALF      NUMBER(1)      NOT NULL,
    INDUSTRY_CD      VARCHAR2(10)   NOT NULL,
    INDUSTRY_NM      VARCHAR2(100)  NOT NULL,
    TOTAL_WORKERS    NUMBER         NOT NULL,
    VACANCY_RATE     NUMBER(5,2),
    HIRE_RATE        NUMBER(5,2),
    SEPARATION_RATE  NUMBER(5,2),
    CONSTRAINT PK_INDUSTRY_VACANCY PRIMARY KEY (PERIOD_YEAR, PERIOD_HALF, INDUSTRY_CD)
);

CREATE TABLE TB_INDUSTRY_EMPLOYMENT (
    PERIOD_YEAR      NUMBER(4)      NOT NULL,
    PERIOD_QUARTER   NUMBER(1)      NOT NULL,
    INDUSTRY_CD      VARCHAR2(10)   NOT NULL,
    INDUSTRY_NM      VARCHAR2(100)  NOT NULL,
    EMPLOYED_COUNT   NUMBER         NOT NULL,
    CONSTRAINT PK_INDUSTRY_EMPLOYMENT PRIMARY KEY (PERIOD_YEAR, PERIOD_QUARTER, INDUSTRY_CD)
);

CREATE TABLE TB_INDUSTRY_INDEX (
    PERIOD_YEAR      NUMBER(4)      NOT NULL,
    PERIOD_QUARTER   NUMBER(1)      NOT NULL,
    INDUSTRY_CD      VARCHAR2(10)   NOT NULL,
    INDUSTRY_NM      VARCHAR2(100)  NOT NULL,
    EMPLOYED_COUNT   NUMBER         NOT NULL,
    GROWTH_RATE      NUMBER(6,2),
    IND_RANK         NUMBER(2),
    CONSTRAINT PK_INDUSTRY_INDEX PRIMARY KEY (PERIOD_YEAR, PERIOD_QUARTER, INDUSTRY_CD)
);

CREATE TABLE TB_INDUSTRY_MAP (
    INDUSTRY_CD      VARCHAR2(10)   NOT NULL,
    INDUSTRY_NM      VARCHAR2(100)  NOT NULL,
    KSIC_CODE        VARCHAR2(30),
    CONSTRAINT PK_INDUSTRY_MAP PRIMARY KEY (INDUSTRY_CD)
);

CREATE TABLE TB_EMPLOYMENT_GENDER (
    PERIOD_YEAR      NUMBER(4)      NOT NULL,
    PERIOD_QUARTER   NUMBER(1)      NOT NULL,
    INDUSTRY_CD      VARCHAR2(10)   NOT NULL,
    GENDER_CD        VARCHAR2(5)    NOT NULL,
    INDUSTRY_NM      VARCHAR2(100)  NOT NULL,
    EMPLOYED_COUNT   NUMBER         NOT NULL,
    CONSTRAINT PK_EMPLOYMENT_GENDER PRIMARY KEY (PERIOD_YEAR, PERIOD_QUARTER, INDUSTRY_CD, GENDER_CD)
);

CREATE TABLE TB_BOARD_POST (
    POST_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INDUSTRY_CD      VARCHAR2(10)   NOT NULL,
    TITLE            VARCHAR2(200)  NOT NULL,
    CONTENT          CLOB,
    AUTHOR           VARCHAR2(50)   NOT NULL,
    CREATED_AT       TIMESTAMP      DEFAULT SYSTIMESTAMP,
    ATTACHMENT_NAME  VARCHAR2(255),
    ATTACHMENT_PATH  VARCHAR2(500)
);
